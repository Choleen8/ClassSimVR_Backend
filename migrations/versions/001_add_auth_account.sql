-- ClassSimVR migration 001: add one authentication account per trainee.
-- Non-destructive and idempotent: existing tables and rows are preserved.
CREATE TABLE IF NOT EXISTS auth_account (
    auth_account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id INTEGER NOT NULL,
    username VARCHAR(80) NOT NULL,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_auth_account_trainee_id UNIQUE (trainee_id),
    CONSTRAINT uq_auth_account_username UNIQUE (username),
    CONSTRAINT uq_auth_account_email UNIQUE (email),
    CONSTRAINT fk_auth_account_trainee
        FOREIGN KEY (trainee_id) REFERENCES trainee (trainee_id) ON DELETE CASCADE
);
